
// greet_and_multiply.js
// ---------------------------
// ฟังก์ชัน greet(name) และ multiply(x, y)
// ---------------------------

// ฟังก์ชันทักทาย
function greet(name) {
  console.log("Hello, " + name + "!");
}

// ฟังก์ชันคูณเลข
function multiply(x, y) {
  return x * y;
}

// ทดสอบเรียกใช้งาน
greet("Nattapong");        // Output: Hello, Nattapong!
console.log(multiply(5, 3)); // Output: 15
